#ifndef PUGE_USER_LAYOUT_H
#define PUGE_USER_LAYOUT_H
/* Positive Sv39 half. Each region is one 4 KiB page. */
#define USER_VA_MAX       0x4000000000
#define USER_CODE_BASE    0x1000
#define USER_BASE         USER_CODE_BASE
#define USER_DATA_BASE    0x2000
#define USER_HEAP_BASE    0x3000
#define TRAMPOLINE       (USER_VA_MAX - 4096)
#define TRAPFRAME        (USER_VA_MAX - 8192)
#define USER_STACK_BASE  (USER_VA_MAX - 12288)
#define USER_STACK_TOP   (USER_STACK_BASE + 4096)
#define USER_STACK_GUARD (USER_VA_MAX - 16384)
#define KERNEL_STACK_BASE (USER_VA_MAX - 20480)
#define KERNEL_STACK_TOP (KERNEL_STACK_BASE + 4096)
#endif
